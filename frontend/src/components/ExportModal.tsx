import React, { useState } from "react";
import { X, Copy, Check, Download, FileCode } from "lucide-react";
import { GraphResponse } from "../types";

interface Props {
  isOpen: boolean;
  onClose: () => void;
  graphData: GraphResponse | null;
  repoName: string;
}

export const ExportModal: React.FC<Props> = ({ isOpen, onClose, graphData, repoName }) => {
  const [copied, setCopied] = useState(false);
  const [exportFormat, setExportFormat] = useState<"mermaid" | "json">("mermaid");

  if (!isOpen || !graphData) return null;

  // Generate Mermaid diagram syntax
  const generateMermaid = () => {
    let lines = ["graph TD", "  %% Generated by TraceFlow Map"];
    graphData.nodes.forEach((n) => {
      const safeLabel = (n.label || n.id).replace(/["()]/g, "");
      lines.push(`  ${n.id.replace(/[^a-zA-Z0-9_]/g, "_")}["${safeLabel}"]`);
    });
    graphData.edges.forEach((e) => {
      const src = e.source.replace(/[^a-zA-Z0-9_]/g, "_");
      const tgt = e.target.replace(/[^a-zA-Z0-9_]/g, "_");
      const label = e.label ? `|"${e.label}"|` : "";
      lines.push(`  ${src} -->${label} ${tgt}`);
    });
    return lines.join("\n");
  };

  const content =
    exportFormat === "mermaid" ? generateMermaid() : JSON.stringify(graphData, null, 2);

  const handleCopy = () => {
    navigator.clipboard.writeText(content);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const ext = exportFormat === "mermaid" ? "mmd" : "json";
    const blob = new Blob([content], { type: "text/plain" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `traceflow_${repoName.replace(/[^a-zA-Z0-9]/g, "_")}.${ext}`;
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="fixed inset-0 z-50 bg-black/70 backdrop-blur-sm flex items-center justify-center p-4">
      <div className="w-full max-w-2xl bg-slate-900 border border-slate-800 rounded-2xl shadow-2xl overflow-hidden flex flex-col max-h-[85vh]">
        {/* Modal Header */}
        <div className="p-4 border-b border-slate-800 flex items-center justify-between">
          <div className="flex items-center space-x-2">
            <FileCode className="text-cyan-400" size={18} />
            <h3 className="text-sm font-bold text-white">Export Architecture Diagram</h3>
          </div>
          <button onClick={onClose} className="text-slate-400 hover:text-white p-1">
            <X size={18} />
          </button>
        </div>

        {/* Format Selector */}
        <div className="px-4 pt-3 flex space-x-2">
          <button
            onClick={() => setExportFormat("mermaid")}
            className={`px-3 py-1 rounded-lg text-xs font-semibold ${
              exportFormat === "mermaid"
                ? "bg-cyan-500 text-slate-950"
                : "bg-slate-800 text-slate-400 hover:text-white"
            }`}
          >
            Mermaid Diagram (.mmd)
          </button>
          <button
            onClick={() => setExportFormat("json")}
            className={`px-3 py-1 rounded-lg text-xs font-semibold ${
              exportFormat === "json"
                ? "bg-cyan-500 text-slate-950"
                : "bg-slate-800 text-slate-400 hover:text-white"
            }`}
          >
            Graph Data (.json)
          </button>
        </div>

        {/* Preview Code Box */}
        <div className="p-4 flex-1 overflow-hidden">
          <pre className="w-full h-80 p-3 bg-slate-950 rounded-xl border border-slate-800 text-xs font-mono text-cyan-300 overflow-auto select-text">
            {content}
          </pre>
        </div>

        {/* Modal Footer Actions */}
        <div className="p-4 border-t border-slate-800 flex items-center justify-between bg-slate-900/60">
          <span className="text-[11px] text-slate-400">
            Paste into GitHub Markdown or Notion to render interactive diagrams.
          </span>
          <div className="flex space-x-2">
            <button
              onClick={handleCopy}
              className="px-3.5 py-1.5 rounded-lg bg-slate-800 hover:bg-slate-700 text-xs font-semibold text-white flex items-center space-x-1.5 border border-slate-700"
            >
              {copied ? <Check size={14} className="text-emerald-400" /> : <Copy size={14} />}
              <span>{copied ? "Copied!" : "Copy"}</span>
            </button>
            <button
              onClick={handleDownload}
              className="px-3.5 py-1.5 rounded-lg bg-cyan-500 hover:bg-cyan-400 text-xs font-bold text-slate-950 flex items-center space-x-1.5 shadow"
            >
              <Download size={14} />
              <span>Download</span>
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};

